"""Public synthetic fixture, not a third-party quantizer or model benchmark."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from roundofflab import Config, quantize, study, render_report
from roundofflab.demo import make_demo
from roundofflab.io import npy_bytes, write_artifacts


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,required=True)
    parser.add_argument('--force',action='store_true')
    args=parser.parse_args()
    w,discovery=make_demo(scenario='quiet-outlier')
    _,validation=make_demo(scenario='active-outlier')
    candidates={'absmax-export':quantize(w,Config()).weights,
                'p95-export':quantize(w,Config(percentile=95)).weights}
    # These fixtures originate from RoundoffLab, then cross the same .npy
    # boundary users employ for their own dequantized exports.
    result=study(w,discovery,validation,candidates=candidates,
                 title='A discovery winner can lose on validation')
    for name,view in result['cohorts'].items():
        view['sample_label']='synthetic / '+name+'; RoundoffLab-generated export fixtures'
    warning='Synthetic counterexample: both export fixtures were generated by RoundoffLab, not a third-party quantizer.'
    result['warnings'].insert(0,warning)
    payloads={'weights.npy':npy_bytes(w),'discovery.npy':npy_bytes(discovery),'validation.npy':npy_bytes(validation),
              'candidates.json':json.dumps({k:k+'.npy' for k in candidates},indent=2).encode(),
              'report.json':(json.dumps(result,indent=2,allow_nan=False)+'\n').encode('utf-8'),
              'index.html':render_report(result).encode('utf-8')}
    payloads.update({name+'.npy':npy_bytes(value) for name,value in candidates.items()})
    write_artifacts(args.out,payloads,force=args.force)
    print(f"Study: {args.out / 'index.html'}")
    print(json.dumps(result['selection']))


if __name__=='__main__':main()
